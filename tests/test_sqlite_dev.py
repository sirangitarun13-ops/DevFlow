def test_sqlite_foreign_key_enforcement() -> None:
    """Verify foreign key constraints are enforced in SQLite."""
    db_url = "sqlite:///:memory:"
    engine = create_engine(
        db_url,
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
    )

    # Enable FK enforcement
    from sqlalchemy import event

    @event.listens_for(engine, "connect")
    def _set_sqlite_pragma(dbapi_connection, connection_record):
        cursor = dbapi_connection.cursor()
        cursor.execute("PRAGMA foreign_keys=ON")
        cursor.execute("PRAGMA journal_mode=WAL")
        cursor.close()

    Base.metadata.create_all(engine)

    with engine.connect() as conn:
        # Verify FK pragma is on
        result = conn.execute(text("PRAGMA foreign_keys")).scalar()
        assert result == 1 or result == "ON"

        # Create a parent and child table to test FK enforcement
        conn.execute(text("CREATE TABLE parent (id INTEGER PRIMARY KEY)"))
        conn.execute(text("CREATE TABLE child (id INTEGER PRIMARY KEY, parent_id INTEGER, FOREIGN KEY(parent_id) REFERENCES parent(id))"))

        # Valid insert should work
        conn.execute(text("INSERT INTO parent (id) VALUES (1)"))
        conn.execute(text("INSERT INTO child (id, parent_id) VALUES (1, 1)"))

        # Invalid FK should raise
        with pytest.raises(Exception):
            conn.execute(text("INSERT INTO child (id, parent_id) VALUES (2, 999)"))


def test_sqlite_uuid_generation() -> None:
    """Verify UUIDs are generated by Python (uuid4) not server defaults."""
    from uuid import uuid4

    from backend.app.models.auth import Role, User
    from backend.app.models.core import Project

    db_url = "sqlite:///:memory:"
    engine = create_engine(
        db_url,
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
    )

    Base.metadata.create_all(engine)

    SessionLocal = sessionmaker(bind=engine, autocommit=False, autoflush=False)

    with SessionLocal() as session:
        # Create a role
        role = Role(code="admin", name="Administrator", description="Test")
        session.add(role)
        session.flush()

        # UUID should be generated by Python
        assert role.id is not None
        # In SQLite with Uuid(as_uuid=True), returns UUID object
        from uuid import UUID
        assert isinstance(role.id, UUID)

        # Create a user - use UUID object for created_by_user_id
        user = User(
            full_name="Test User",
            email="test@example.com",
            password_hash="hashed",
        )
        session.add(user)
        session.flush()

        assert user.id is not None
        assert isinstance(user.id, UUID)

        # Create a project - use UUID object for created_by_user_id
        project = Project(name="Test Project", created_by_user_id=user.id)
        session.add(project)
        session.flush()

        assert project.id is not None
        assert isinstance(project.id, UUID)


